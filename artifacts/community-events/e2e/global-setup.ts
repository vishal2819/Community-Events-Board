import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import path from "node:path";
import { PrismaClient } from "@prisma/client";
import { defaultTestDatabaseUrl, maintenanceUrl, resolveAdminCredentials } from "./runtime";

const projectRoot = path.resolve(import.meta.dirname, "..");
const requireFromProject = createRequire(path.join(projectRoot, "noop.js"));

function databaseName(url: string): string {
  return new URL(url).pathname.replace(/^\//, "");
}

async function ensureDatabaseExists(url: string): Promise<void> {
  const admin = new PrismaClient({ datasources: { db: { url: maintenanceUrl(url) } } });
  try {
    await admin.$executeRawUnsafe(`CREATE DATABASE "${databaseName(url)}"`);
  } catch (error) {
    // Prisma reports a failed raw statement as P2010 and carries the Postgres
    // status in meta.code; 42P04 is duplicate_database, so setup stays re-runnable.
    const wrapperCode = (error as { code?: string }).code;
    const postgresCode = (error as { meta?: { code?: string } }).meta?.code;
    if (wrapperCode !== "42P04" && postgresCode !== "42P04") throw error;
  } finally {
    await admin.$disconnect();
  }
}

/**
 * Runs a CLI entry point through the current Node binary. Going via `node`
 * avoids both `shell: true` (arguments would not be escaped) and the
 * `spawnSync pnpm.cmd EINVAL` failure Node 24 raises for batch files.
 */
function node(entry: string, args: string[], env: NodeJS.ProcessEnv): void {
  execFileSync(process.execPath, [entry, ...args], {
    cwd: projectRoot,
    env,
    stdio: "inherit",
  });
}

export default async function globalSetup(): Promise<void> {
  const databaseUrl = defaultTestDatabaseUrl();

  // Validates admin credentials and refuses to run if `.env` would shadow them.
  resolveAdminCredentials();

  await ensureDatabaseExists(databaseUrl);

  const env = { ...process.env, DATABASE_URL: databaseUrl };

  // The Prisma client is generated by `pnpm db:generate` (and by `pnpm build`).
  // Regenerating it here would fight the running development server for a lock on
  // the query engine, so setup only applies the committed migrations instead.
  node(requireFromProject.resolve("prisma/build/index.js"), ["migrate", "deploy"], env);

  // `tsx/cli` is the executable entry point. The bare `tsx` export is only a
  // loader module and would register hooks without ever running the seed script.
  node(requireFromProject.resolve("tsx/cli"), [path.join(projectRoot, "prisma", "seed.ts")], env);

  // Seeded events are deterministic and kept, but per-user rows from an earlier
  // run would otherwise leak into this one.
  const db = new PrismaClient({ datasources: { db: { url: databaseUrl } } });
  try {
    await db.$executeRawUnsafe(
      'TRUNCATE TABLE "EventCardDesign", "EventReminder", "FavouriteCategory", "User" CASCADE',
    );
  } finally {
    await db.$disconnect();
  }
}